async function updateDomains() {
  const proxied = new Set();
  const direct = new Set();
  const stats = [];
  let okSources = 0;

  for (const src of SOURCES) {
    try {
      const text = await fetchSource(src);
      let n = 0;
      for (const line of text.split(/\r?\n/)) {
        const d = normalizeDomain(line);
        if (!d) continue;
        (src.target === 'direct' ? direct : proxied).add(d);
        n++;
      }
      stats.push(`${src.name}: ${n}`);
      okSources++;
      console.log(`  [${src.name}] получено ${n} доменов`);
    } catch (e) {
      stats.push(`${src.name}: FAIL`);
      console.log(`  [${src.name}] недоступен, пропускаю (${String(e.message).slice(0, 80)})`);
    }
  }

  const extra = readExtraDomains();
  for (const d of extra) proxied.add(d);
  if (extra.length) stats.push(`extra: ${extra.length}`);

  if (okSources === 0 && extra.length === 0) {
    throw new Error('ни один источник не ответил, proxy.pac не изменён');
  }

  const prunedProxy = pruneSubdomains(proxied);
  const prunedDirect = pruneSubdomains(direct);
  if (prunedProxy || prunedDirect) {
    console.log(`  убрано поддоменов, покрытых родительскими: ${prunedProxy} (VPN) + ${prunedDirect} (DIRECT)`);
  }

  fs.writeFileSync(OUT_PAC, buildPac());

  console.log(
    `списки обновлены: ${proxied.size} через VPN, ${direct.size} исключений (${stats.join(', ')})`
  );
  return { proxied: Array.from(proxied).sort(), direct: Array.from(direct).sort() };
}

module.exports = { updateDomains, normalizeDomain };

if (require.main === module) {
  updateDomains().catch((e) => {
    console.error('ОШИБКА:', e.message);
    process.exit(1);
  });
}
