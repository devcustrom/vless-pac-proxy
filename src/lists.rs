//! Загрузка списков доменов (itdog inside/outside, refilter), нормализация,
//! pruning и генерация PAC. Аналог legacy update-domains.js.
use std::collections::HashSet;
use std::path::Path;
use std::sync::{Arc, OnceLock};

use anyhow::{bail, Result};
use regex::Regex;

use crate::state::AppState;
use crate::wlog;

pub const MODE: &str = "blocked-only";

const SOURCES: [(&str, bool, &str); 3] = [
    (
        "itdog",
        false,
        "https://raw.githubusercontent.com/itdoginfo/allow-domains/main/Russia/inside-raw.lst",
    ),
    (
        "itdog-direct",
        true,
        "https://raw.githubusercontent.com/itdoginfo/allow-domains/main/Russia/outside-raw.lst",
    ),
    (
        "refilter",
        false,
        "https://raw.githubusercontent.com/1andrevich/Re-filter-lists/main/domains_all.lst",
    ),
];

fn domain_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| {
        Regex::new(r"^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$").unwrap()
    })
}

fn tld_re() -> &'static Regex {
    static RE: OnceLock<Regex> = OnceLock::new();
    RE.get_or_init(|| Regex::new(r"^[a-z]{2,24}$").unwrap())
}

pub fn normalize_domain(line: &str) -> Option<String> {
    let mut d = line.trim().to_lowercase();
    if d.is_empty() || d.starts_with('#') || d.starts_with('!') || d.starts_with(';') {
        return None;
    }
    // сначала снимаем схему (https://...), иначе от неё остаётся «https»
    d = d
        .trim_start_matches("https://")
        .trim_start_matches("http://")
        .to_string();
    d = d.split('/').next()?.split(':').next()?.to_string();
    // IP-литералы — не домены
    if d.parse::<std::net::IpAddr>().is_ok() {
        return None;
    }
    d = d
        .trim_start_matches("*.")
        .trim_start_matches('.')
        .trim_start_matches("www.")
        .to_string();
    if let Some(stripped) = d.strip_suffix('.') {
        d = stripped.to_string();
    }
    if tld_re().is_match(&d) {
        return Some(d);
    }
    if domain_re().is_match(&d) {
        Some(d)
    } else {
        None
    }
}

/// Убирает поддомены, если родитель уже есть в наборе.
pub fn prune_subdomains(set: &mut HashSet<String>) -> usize {
    let mut drop = Vec::new();
    for d in set.iter() {
        let labels: Vec<&str> = d.split('.').collect();
        for i in 1..labels.len() {
            let parent = labels[i..].join(".");
            if set.contains(&parent) {
                drop.push(d.clone());
                break;
            }
        }
    }
    for d in &drop {
        set.remove(d);
    }
    drop.len()
}

pub fn read_domain_file(dir: &Path, name: &str) -> Vec<String> {
    let Ok(path) = crate::paths::in_dir(dir, name) else {
        return Vec::new();
    };
    let Ok(text) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    text.lines().filter_map(normalize_domain).collect()
}

pub fn pac_content() -> String {
    format!(
        "// AUTO-GENERATED by wireproxy-control — маршрутизацию выполняет менеджер\n\
         function FindProxyForURL(url, host) {{\n\
         \x20   host = String(host).toLowerCase();\n\
         \x20   if (isPlainHostName(host) || host === \"localhost\" || shExpMatch(host, \"*.local\")) return \"DIRECT\";\n\
         \x20   if (/^\\d{{1,3}}(\\.\\d{{1,3}}){{3}}$/.test(host)) return \"DIRECT\";\n\
         \x20   return \"PROXY 127.0.0.1:{}; DIRECT\";\n\
         }}\n",
        crate::api::SMART_PROXY_PORT
    )
}

async fn fetch_text(state: &Arc<AppState>, url: &str) -> Result<String> {
    let direct = state.client("lists-direct", None);
    match direct.get(url).send().await {
        Ok(resp) => {
            if !resp.status().is_success() {
                bail!("HTTP {}", resp.status());
            }
            Ok(resp.text().await?)
        }
        Err(first_err) => {
            // запасной путь: через собственный прокси (если туннель работает)
            let proxied = state.client("lists-proxy", Some(crate::vless::WIREPROXY_HTTP_PORT));
            let resp = proxied
                .get(url)
                .send()
                .await
                .map_err(|e| anyhow::anyhow!("{first_err}; через прокси: {e}"))?;
            if !resp.status().is_success() {
                bail!("HTTP {} (через прокси)", resp.status());
            }
            Ok(resp.text().await?)
        }
    }
}

pub async fn refresh(state: &Arc<AppState>) -> Result<()> {
    {
        let mut lists = state.lists.lock().unwrap();
        if lists.refreshing {
            bail!("обновление уже идёт");
        }
        lists.refreshing = true;
    }

    let mut proxied: HashSet<String> = HashSet::new();
    let mut direct: HashSet<String> = HashSet::new();
    let mut ok_sources = 0usize;
    let mut stats: Vec<String> = Vec::new();

    for (name, is_direct, url) in SOURCES {
        match fetch_text(state, url).await {
            Ok(text) => {
                let mut n = 0usize;
                for line in text.lines() {
                    if let Some(d) = normalize_domain(line) {
                        if is_direct {
                            direct.insert(d);
                        } else {
                            proxied.insert(d);
                        }
                        n += 1;
                    }
                }
                stats.push(format!("{name}: {n}"));
                ok_sources += 1;
                wlog!("список {name}: {n} доменов");
            }
            Err(e) => {
                stats.push(format!("{name}: FAIL"));
                wlog!("список {name}: ошибка — {e}");
            }
        }
    }

    let extra = read_domain_file(&state.dir, "extra-domains.txt");
    for d in &extra {
        proxied.insert(d.clone());
    }
    let vless_only: HashSet<String> = read_domain_file(&state.dir, "vless-domains.txt")
        .into_iter()
        .collect();

    if ok_sources == 0 && extra.is_empty() {
        let mut lists = state.lists.lock().unwrap();
        lists.refreshing = false;
        lists.error = Some("ни один источник не ответил, списки не изменены".into());
        bail!("ни один источник не ответил");
    }

    let pruned_p = prune_subdomains(&mut proxied);
    let pruned_d = prune_subdomains(&mut direct);

    let pac_path = crate::paths::in_dir(&state.dir, "proxy.pac")?;
    std::fs::write(pac_path, pac_content())?;

    {
        let mut lists = state.lists.lock().unwrap();
        lists.proxied = proxied;
        lists.direct = direct;
        lists.vless_only = vless_only;
        lists.last_update = Some(chrono::Utc::now());
        lists.error = None;
        lists.refreshing = false;
    }

    let lists = state.lists.lock().unwrap();
    wlog!(
        "списки обновлены: {} через VPN, {} исключений ({}), pruning {}+{}",
        lists.proxied.len(),
        lists.direct.len(),
        stats.join(", "),
        pruned_p,
        pruned_d
    );
    Ok(())
}

pub fn spawn_scheduler(state: Arc<AppState>) {
    tokio::spawn(async move {
        tokio::time::sleep(std::time::Duration::from_secs(5)).await;
        if let Err(e) = refresh(&state).await {
            wlog!("стартовое обновление списков: {e}");
        }
        loop {
            tokio::time::sleep(std::time::Duration::from_secs(12 * 60 * 60)).await;
            if let Err(e) = refresh(&state).await {
                wlog!("плановое обновление списков: {e}");
            }
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn normalize_cases() {
        assert_eq!(
            normalize_domain(" Example.COM "),
            Some("example.com".into())
        );
        assert_eq!(
            normalize_domain("*.foo.example.com"),
            Some("foo.example.com".into())
        );
        assert_eq!(normalize_domain(".ua"), Some("ua".into()));
        assert_eq!(normalize_domain("https://x.com/path"), Some("x.com".into()));
        assert_eq!(normalize_domain("10.0.0.0/8"), None);
        assert_eq!(normalize_domain("1.2.3.4"), None);
        assert_eq!(normalize_domain("# comment"), None);
    }

    #[test]
    fn pruning_keeps_parents() {
        let mut set: HashSet<String> = [
            "example.com",
            "a.example.com",
            "deep.a.example.com",
            "other.org",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect();
        let dropped = prune_subdomains(&mut set);
        assert_eq!(dropped, 2);
        assert!(set.contains("example.com"));
        assert!(set.contains("other.org"));
    }

    #[test]
    fn pac_mentions_proxy() {
        assert!(pac_content().contains("PROXY 127.0.0.1:8081"));
    }
}
